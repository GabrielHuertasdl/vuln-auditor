"""
Generates a structured Markdown report from a completed ScanResult.

Report structure:
  1. Header (metadata, disclaimer)
  2. Risk metrics (Business Risk Score, Posture)
  3. Historical trend (Diff vs previous)
  4. Executive summary
  5. Severity + Priority overview
  6. Detected stack
  7. Top findings (most urgent, max 5)
  8. Quick wins (high-impact, low-effort)
  9. All findings (sorted by priority → severity → confidence)
  10. Noise / low-confidence observations
  11. Tool summary
  12. Appendix
"""
from __future__ import annotations

import re
import hashlib
import urllib.parse
from datetime import datetime, UTC
from typing import NamedTuple

from core.schemas import (
    Confidence,
    Exploitability,
    Finding,
    Priority,
    RemediationEffort,
    Severity,
    ScanResult,
)

_SEV_ICON = {
    Severity.CRITICAL: "🔴 CRITICAL",
    Severity.HIGH: "🟠 HIGH",
    Severity.MEDIUM: "🟡 MEDIUM",
    Severity.LOW: "🔵 LOW",
    Severity.INFORMATIONAL: "⚪ INFO",
}

_PRI_ICON = {
    Priority.IMMEDIATE: "🚨 IMMEDIATE",
    Priority.HIGH: "🔴 HIGH",
    Priority.MEDIUM: "🟡 MEDIUM",
    Priority.LOW: "🟢 LOW",
    Priority.DEFERRED: "⬜ DEFERRED",
}

_EFFORT_LABEL = {
    RemediationEffort.MINUTES: "⚡ Minutes",
    RemediationEffort.HOURS: "🕐 Hours",
    RemediationEffort.DAYS: "📅 Days",
    RemediationEffort.WEEKS: "🗓️ Weeks",
}

_EXPLOIT_LABEL = {
    Exploitability.EASY: "🔓 Easy",
    Exploitability.MODERATE: "🔐 Moderate",
    Exploitability.DIFFICULT: "🔒 Difficult",
    Exploitability.UNKNOWN: "❓ Unknown",
}

_SEVERITY_ORDER = [Severity.CRITICAL, Severity.HIGH, Severity.MEDIUM, Severity.LOW, Severity.INFORMATIONAL]
_PRIORITY_ORDER = [Priority.IMMEDIATE, Priority.HIGH, Priority.MEDIUM, Priority.LOW, Priority.DEFERRED]
_CONFIDENCE_ORDER = [Confidence.HIGH, Confidence.MEDIUM, Confidence.LOW]


def _sort_key(f: Finding) -> tuple:
    pri = _PRIORITY_ORDER.index(f.priority) if f.priority in _PRIORITY_ORDER else 99
    sev = _SEVERITY_ORDER.index(f.severity) if f.severity in _SEVERITY_ORDER else 99
    conf = _CONFIDENCE_ORDER.index(f.confidence) if f.confidence in _CONFIDENCE_ORDER else 99
    return (pri, sev, conf, f.title.lower())


def _active_findings(scan: ScanResult) -> list[Finding]:
    """Non-noise, non-duplicate findings sorted by priority."""
    return sorted(
        [f for f in scan.findings if not f.is_noise and not f.duplicate_of],
        key=_sort_key,
    )


def _noise_findings(scan: ScanResult) -> list[Finding]:
    return [f for f in scan.findings if f.is_noise or f.duplicate_of]


def generate_report(scan: ScanResult) -> str:
    lines: list[str] = []
    active = _active_findings(scan)
    noise = _noise_findings(scan)

    _section_header(lines, scan)
    _section_disclaimer(lines)
    _section_risk_metrics(lines, scan, active)
    _section_posture_trends(lines, scan)
    _section_verifications(lines, scan)
    _section_historical_trend(lines, scan)
    _section_executive_summary(lines, scan, active)
    _section_overview(lines, scan, active)
    _section_stack(lines, scan)
    _section_top_findings(lines, active)
    _section_quick_wins(lines, active)
    _section_all_findings(lines, active)
    _section_noise(lines, noise)
    _section_tools(lines, scan)
    _section_appendix(lines, scan)

    return "\n".join(lines)


# ── Section builders ──────────────────────────────────────────────────────────

def _section_header(lines: list[str], scan: ScanResult) -> None:
    lines += [
        "# Security Scan Report",
        "",
        "| Field | Value |",
        "|-------|-------|",
        f"| **Scan ID** | `{scan.scan_id}` |",
        f"| **Target** | `{scan.target}` |",
        f"| **Status** | {scan.status.value.upper()} |",
        f"| **Mode** | {scan.scan_mode} |",
        f"| **Date** | {(scan.completed_at or datetime.now(UTC)).strftime('%Y-%m-%d %H:%M UTC')} |",
    ]
    if scan.duration_seconds:
        lines.append(f"| **Duration** | {scan.duration_seconds:.1f}s |")
    lines.append("")


def _section_disclaimer(lines: list[str]) -> None:
    lines += [
        "> **⚠️ IMPORTANT — Authorized use only.**",
        "> This report was generated by an automated security scanner.",
        "> All findings must be verified manually before acting on them.",
        "> Automated scanners produce false positives. Exploitability",
        "> and impact assessments are estimates based on available evidence,",
        "> not confirmed exploitation. Use only on systems you are authorized to test.",
        "",
    ]


def _section_risk_metrics(lines: list[str], scan: ScanResult, active: list[Finding]) -> None:
    if scan.posture_score:
        ps = scan.posture_score
        # Posture Grade based on overall score (0-100)
        grade = "A" if ps.overall_score >= 90 else "B" if ps.overall_score >= 75 else "C" if ps.overall_score >= 50 else "D" if ps.overall_score >= 30 else "F"
        grade_icon = "✅" if grade == "A" else "⚠️" if grade in "BC" else "❌"
        
        lines += [
            "## ⚖️ Security Posture Intelligence",
            "",
            f"| Overall Posture Score | Posture Grade | Verification Coverage | Evidence Confidence |",
            f"|:---------------------:|:-------------:|:---------------------:|:-------------------:|",
            f"| **{ps.overall_score}/100** | **{grade}** | {ps.coverage_score}% | {ps.confidence_score}% |",
            "",
            "> *The Posture Score represents the overall health of verified security controls and coverage.*",
            "",
        ]
        return

    from core.scorer import calculate_business_risk_score
    
    # Calculate aggregate risk score
    scores = [
        calculate_business_risk_score(f.severity, getattr(f, "business_impact", None))
        for f in active
    ]
    
    max_score = max(scores) if scores else 0
    density_factor = min(len(active) * 2, 20)
    total_risk = min(max_score + density_factor, 100)
    
    # Posture Grade
    grade = "A" if total_risk < 20 else "B" if total_risk < 40 else "C" if total_risk < 60 else "D" if total_risk < 80 else "F"
    grade_icon = "✅" if grade == "A" else "⚠️" if grade in "BC" else "❌"
    
    lines += [
        "## ⚖️ Risk Intelligence",
        "",
        f"| Business Risk Score | Posture Grade | Security Status |",
        f"|:-------------------:|:-------------:|:---------------:|",
        f"| **{total_risk}/100** | **{grade}** | {grade_icon} |",
        "",
        "> *The Risk Score is a weighted calculation of technical severity, impact, and finding density.*",
        "",
    ]


def _section_posture_trends(lines: list[str], scan: ScanResult) -> None:
    if not scan.posture_diff or not scan.posture_diff.score_trend:
        return

    diff = scan.posture_diff
    trend = diff.score_trend

    def _fmt_change(val: float) -> str:
        if val > 0:
            return f"🟢 +{val} ↑"
        elif val < 0:
            return f"🔴 {val} ↓"
        return "⚪ No change"

    lines += [
        "## 📈 Security Posture Trends",
        "",
        "Changes compared to the previous baseline scan:",
        "",
        "| Metric | Change | Current Value |",
        "|:---|:---|:---|",
        f"| **Overall Score** | {_fmt_change(trend.overall_change)} | {scan.posture_score.overall_score if scan.posture_score else '-'} |",
        f"| **Coverage** | {_fmt_change(trend.coverage_change)} | {scan.posture_score.coverage_score if scan.posture_score else '-'}% |",
        f"| **Confidence** | {_fmt_change(trend.confidence_change)} | {scan.posture_score.confidence_score if scan.posture_score else '-'}% |",
        "",
    ]

    if trend.breakdown_delta:
        lines += ["### 🔍 Posture Delta Breakdown", ""]
        lines += [
            "| Control | Impact on Score | Explanation |",
            "|:---|:---|:---|",
        ]
        for cid, delta in sorted(trend.breakdown_delta.items(), key=lambda x: x[1]):
            icon = "🔻" if delta < 0 else "🔋"
            lines.append(f"| `{cid}` | {icon} {delta:+.1f} | Change in verification status contribution |")
        lines.append("")

    if diff.regressions:
        lines += ["### ⚠️ Regressions Detected", ""]
        for r in diff.regressions:
            labels = {
                "critical": "🚨 CRITICAL REGRESSION",
                "coverage": "🔍 COVERAGE GAP",
                "suspected": "⚠️ SUSPECTED REGRESSION",
                "confirmed_failure": "❌ CONFIRMED FAILURE",
            }
            label = labels.get(r.type, "⚠️ REGRESSION")
            lines.append(f"- **{r.control_id}**: {label}")
            lines.append(f"  - Changed from `{r.previous_status.value}` to `{r.current_status.value}`")
            if r.reason:
                lines.append(f"  - *Reason: {r.reason}*")
        lines.append("")

    if diff.persistent_fails or diff.persistent_coverage_gaps:
        lines += ["### 🔄 Persistent Issues", ""]
        lines.append("> These issues have persisted since the previous scan and require attention:")
        for pf in diff.persistent_fails:
            lines.append(f"- **{pf}**: ❌ Persistent Failure")
        for pg in diff.persistent_coverage_gaps:
            lines.append(f"- **{pg}**: ❔ Persistent Coverage Gap (Insufficient Evidence)")
        lines.append("")

    if diff.improvements:
        lines += ["### ✨ Improvements", ""]
        for i in diff.improvements:
            labels = {
                "verification": "✅ VERIFIED FIX",
                "reduction": "📉 RISK REDUCTION",
                "visibility": "🔭 VISIBILITY GAIN",
            }
            label = labels.get(i.type, "✨ IMPROVEMENT")
            lines.append(f"- **{i.control_id}**: {label} (from `{i.previous_status.value}` to `{i.current_status.value}`)")
        lines.append("")


def _section_verifications(lines: list[str], scan: ScanResult) -> None:
    if not scan.verifications:
        return

    lines += ["## ✅ Security Control Verifications", ""]

    lines += [
        "| Control | Status | Evidence |",
        "|:---|:---|:---|",
    ]

    status_icons = {
        "verified_pass": "✅ PASS",
        "verified_fail": "❌ FAIL",
        "suspected_issue": "⚠️ SUSPECTED",
        "insufficient_evidence": "❔ INSUFFICIENT",
        "not_applicable": "➖ N/A",
    }

    for v in scan.verifications:
        icon = status_icons.get(v.status.value, v.status.value)
        evidence = v.evidence_summary or "No direct evidence provided."
        lines.append(f"| **{v.control_id}** | {icon} | {evidence} |")

    lines.append("")


def _section_historical_trend(lines: list[str], scan: ScanResult) -> None:
    # Only show if there's historical data
    if not any([scan.new_findings_count, scan.resolved_findings_count, scan.regressed_findings_count]):
        return

    lines += [
        "## 📉 Historical Trends",
        "",
        "Comparison with previous audit baseline:",
        "",
        "| Metric | Count | Change |",
        "|--------|-------|--------|",
        f"| ✨ New Findings | {scan.new_findings_count} | ![New](https://img.shields.io/badge/-New-blue) |",
        f"| ✅ Resolved | {scan.resolved_findings_count} | ![Fixed](https://img.shields.io/badge/-Fixed-green) |",
        f"| ⚠️ Regressions | {scan.regressed_findings_count} | ![Regressed](https://img.shields.io/badge/-Regressed-red) |",
        "",
    ]


def _section_executive_summary(lines: list[str], scan: ScanResult, active: list[Finding]) -> None:
    lines.append("## Executive Summary")
    lines.append("")

    if scan.ai_executive_summary:
        lines.append("> AI-generated summary — verify against scanner evidence.")
        lines.append("")
        lines.append(scan.ai_executive_summary)
    else:
        critical = sum(1 for f in active if f.severity == Severity.CRITICAL)
        high = sum(1 for f in active if f.severity == Severity.HIGH)
        immediate = sum(1 for f in active if f.priority == Priority.IMMEDIATE)
        quick = _get_quick_wins(active)

        lines.append(
            f"Scan completed with **{len(active)} actionable finding(s)** "
            f"({critical} critical, {high} high)."
        )
        if immediate:
            lines.append(f"**{immediate} finding(s) require immediate attention.**")
        if quick:
            lines.append(
                f"**{len(quick)} quick win(s)** identified — high-impact fixes "
                f"achievable in minutes or hours."
            )
    lines.append("")


def _section_overview(lines: list[str], scan: ScanResult, active: list[Finding]) -> None:
    lines += ["## Overview", ""]

    lines += [
        "### By Severity",
        "",
        "| Severity | Count |",
        "|----------|-------|",
    ]
    for sev in _SEVERITY_ORDER:
        count = scan.severity_summary.get(sev.value, 0)
        lines.append(f"| {_SEV_ICON[sev]} | {count} |")
    lines.append("")

    lines += [
        "### By Priority",
        "",
        "| Priority | Count | Meaning |",
        "|----------|-------|---------|",
        "| 🚨 IMMEDIATE | " + str(scan.priority_summary.get('immediate', 0)) + " | Fix now |",
        "| 🔴 HIGH | " + str(scan.priority_summary.get('high', 0)) + " | Fix this sprint |",
        "| 🟡 MEDIUM | " + str(scan.priority_summary.get('medium', 0)) + " | Fix this quarter |",
        "| 🟢 LOW | " + str(scan.priority_summary.get('low', 0)) + " | Fix when convenient |",
        "| ⬜ DEFERRED | " + str(scan.priority_summary.get('deferred', 0)) + " | Accepted risk / noise |",
        "",
    ]


def _section_stack(lines: list[str], scan: ScanResult) -> None:
    if not scan.detected_stack:
        return
    lines += [
        "## Detected Stack",
        "",
        "The following technologies were inferred from scanner output:",
        "",
    ]
    for tech in scan.detected_stack:
        lines.append(f"- {tech}")
    lines.append("")


def _section_top_findings(lines: list[str], active: list[Finding]) -> None:
    urgent = [f for f in active if f.priority in (Priority.IMMEDIATE, Priority.HIGH)][:5]
    if not urgent:
        return

    lines += ["## Top Findings", "", "The 5 most urgent issues requiring attention:", ""]
    lines += [
        "| # | Title | Severity | Priority | Exploitability | Effort |",
        "|---|-------|----------|----------|----------------|--------|",
    ]
    for i, f in enumerate(urgent, 1):
        lines.append(
            f"| {i} | {f.title[:60]} | {_SEV_ICON[f.severity]} | "
            f"{_PRI_ICON[f.priority]} | {_EXPLOIT_LABEL[f.exploitability]} | "
            f"{_EFFORT_LABEL[f.remediation_effort]} |"
        )
    lines.append("")


def _get_quick_wins(active: list[Finding]) -> list[Finding]:
    """High-severity findings fixable in minutes or hours."""
    return [
        f for f in active
        if f.severity in (Severity.CRITICAL, Severity.HIGH, Severity.MEDIUM)
        and f.remediation_effort in (RemediationEffort.MINUTES, RemediationEffort.HOURS)
        and f.priority in (Priority.IMMEDIATE, Priority.HIGH, Priority.MEDIUM)
    ]


def _section_quick_wins(lines: list[str], active: list[Finding]) -> None:
    quick = _get_quick_wins(active)
    if not quick:
        return

    lines += [
        "## Quick Wins",
        "",
        "High-impact findings that can be fixed quickly (minutes to hours):",
        "",
        "| Title | Severity | Effort | OWASP |",
        "|-------|----------|--------|-------|",
    ]
    for f in quick[:10]:
        owasp = f.owasp_category or f.owasp_api_category or "—"
        lines.append(
            f"| {f.title[:55]} | {_SEV_ICON[f.severity]} | "
            f"{_EFFORT_LABEL[f.remediation_effort]} | {owasp} |"
        )
    lines.append("")


def _section_all_findings(lines: list[str], active: list[Finding]) -> None:
    lines += ["## Findings", ""]
    if not active:
        lines += ["No actionable findings detected.", ""]
        return
    for f in active:
        _render_finding(lines, f)


def _section_noise(lines: list[str], noise: list[Finding]) -> None:
    if not noise:
        return
    lines += [
        "## Noise / Low-Confidence Observations",
        "",
        "> The following findings have low confidence, are duplicates, or were marked as noise.",
        "> Review manually — they may be false positives or require more context.",
        "",
        "| Title | Host | Confidence | Reason |",
        "|-------|------|------------|--------|",
    ]
    for f in noise[:20]:
        reason = "duplicate" if f.duplicate_of else ("noise" if f.is_noise else "low confidence")
        lines.append(
            f"| {f.title[:50]} | {f.host} | {f.confidence.value} | {reason} |"
        )
    lines.append("")


def _section_tools(lines: list[str], scan: ScanResult) -> None:
    lines += ["## Tool Summary", ""]
    for tool in scan.tools_requested:
        if tool in scan.tools_succeeded:
            lines.append(f"- **{tool.value.upper()}**: ✅ Completed")
        elif tool.value in scan.tools_failed:
            reason = scan.tools_failed[tool.value]
            lines.append(f"- **{tool.value.upper()}**: ❌ {reason}")
        else:
            lines.append(f"- **{tool.value.upper()}**: ⚠️ Unknown")
    lines.append("")


def _section_appendix(lines: list[str], scan: ScanResult) -> None:
    lines += [
        "---",
        "## Appendix",
        "",
        f"- Scan data: `data/scans/{scan.scan_id}/`",
        f"- Normalized findings: `data/scans/{scan.scan_id}/normalized.json`",
        f"- Raw tool outputs: `data/scans/{scan.scan_id}/raw/`",
        "",
        "*Report generated by Vulnerability Auditor v0.3.0*",
        "*All findings require manual verification before remediation.*",
    ]


# ── Finding renderer ──────────────────────────────────────────────────────────

def _render_finding(lines: list[str], f: Finding) -> None:
    lines += [
        f"### {_SEV_ICON[f.severity]} — {f.title}",
        "",
        "| Field | Value |",
        "|-------|-------|",
        f"| **Severity** | `{f.severity.value}` |",
        f"| **Priority** | {_PRI_ICON[f.priority]} |",
        f"| **Confidence** | `{f.confidence.value}` |",
        f"| **Exploitability** | {_EXPLOIT_LABEL[f.exploitability]} |",
        f"| **Remediation effort** | {_EFFORT_LABEL[f.remediation_effort]} |",
        f"| **Host** | `{f.host}` |",
    ]

    if f.port:
        lines.append(f"| **Port** | `{f.port}/{f.protocol}` |")
    if f.path and f.path != "/":
        lines.append(f"| **Path** | `{f.path}` |")
    if f.method:
        lines.append(f"| **Method** | `{f.method}` |")
    if f.parameter:
        lines.append(f"| **Parameter** | `{f.parameter}` |")
    if f.owasp_category:
        lines.append(f"| **OWASP Top 10** | {f.owasp_category} |")
    if f.owasp_api_category:
        lines.append(f"| **OWASP API Top 10** | {f.owasp_api_category} |")
    if f.cwe_ids:
        cwe_links = ", ".join(
            f"[CWE-{c}](https://cwe.mitre.org/data/definitions/{c}.html)" for c in f.cwe_ids
        )
        lines.append(f"| **CWE** | {cwe_links} |")
    lines.append(f"| **Sources** | {', '.join(t.value for t in f.sources)} ({f.source_count} tool(s)) |")

    if f.detected_stack:
        lines.append(f"| **Stack context** | {', '.join(f.detected_stack[:4])} |")

    lines.append("")

    lines += ["**Description**", "", f.description[:1000], ""]

    if f.normalized_evidence or f.evidence:
        evidence_display = f.normalized_evidence or f.evidence
        lines += [
            "**Evidence** *(dynamic values redacted)*",
            "",
            "```",
            (evidence_display or "")[:800],
            "```",
            "",
        ]

    if f.ai_mitigation:
        lines += [
            "**Recommended Mitigation**",
            "",
            "> ⚠️ AI-generated. Verify against scanner evidence before acting.",
            "",
            f.ai_mitigation,
            "",
        ]
    elif f.solution:
        lines += ["**Recommended Mitigation**", "", f.solution, ""]

    if f.references:
        lines += ["**References**", ""]
        for ref in f.references[:5]:
            lines.append(f"- {ref}")
        lines.append("")

    if f.related_findings:
        lines.append(f"*Related findings: {len(f.related_findings)} finding(s) share the same vulnerability class.*")
        lines.append("")

    lines += ["---", ""]
